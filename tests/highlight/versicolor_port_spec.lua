describe('Versicolor port', function()
  it('matches the recovered Neovim canvas and JavaScript colors', function()
    require('argiope').setup({ theme = { variant = 'versicolor' } })
    vim.cmd.colorscheme('argiope-versicolor')
    local profile = require('argiope.palette').profile('versicolor')
    assert.are.equal('#05070B', profile.base.bg)
    local js = profile.languages.javascript
    assert.are.equal('#FFD8B0', js.colors.main)
    assert.are.equal('#F8B200', js.colors.dim)
    assert.are.equal('#FCA746', js.colors.soft)
    assert.are.equal('#91E090', js.colors.accent)
    assert.are.equal('#9D7462', js.colors.muted)
    local function fg(name) return vim.api.nvim_get_hl(0, { name = name, link = false }).fg end
    assert.are.equal(0xD3CBB0, fg('@variable.javascript'))
    assert.are.equal(0xF8B200, fg('@argiope.const.variable.javascript'))
    assert.are.equal(0xFCA746, fg('@variable.member.javascript'))
    assert.are.equal(0x91E090, fg('@string.javascript'))
    assert.are.equal(0x9D7462, fg('@operator.javascript'))
    assert.are.equal(0x05070B, vim.api.nvim_get_hl(0, { name = 'Normal', link = false }).bg)
  end)
end)
